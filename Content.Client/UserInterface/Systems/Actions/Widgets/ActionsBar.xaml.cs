using Content.Client.UserInterface.Systems.Chat;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Systems.Actions.Widgets;

[GenerateTypedNameReferences]
public sealed partial class ActionsBar : UIWidget
{
    public ActionsBar()
    {
        RobustXamlLoader.Load(this);

        var chatController = UserInterfaceManager.GetUIController<ChatUIController>();
        UpdateCombatModeButton(chatController.CombatPanelModeEnabled);
        CombatPanelModeButton.OnPressed += _ =>
        {
            var enabled = chatController.ToggleCombatPanelMode();
            UpdateCombatModeButton(enabled);
        };
    }

    private void UpdateCombatModeButton(bool enabled)
    {
        CombatPanelModeButton.Text = enabled ? "РП: ВКЛ" : "РП: ВЫКЛ";
        if (enabled)
            CombatPanelModeButton.StyleClasses.Add("positive");
        else
            CombatPanelModeButton.StyleClasses.Remove("positive");
    }
}

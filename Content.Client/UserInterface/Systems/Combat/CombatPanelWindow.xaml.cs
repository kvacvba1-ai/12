    private void BeginTreatmentMiniGame(
        string itemName,
        EntityUid item,
        CombatPanelTreatmentType type,
        TargetBodyPart part)
    {
        _pendingTreatmentItem = item;
        _pendingTreatmentType = type;
        _pendingTreatmentPart = part;
        _pendingAttackMessage = $"медицинская процедура: {itemName}";
        _miniGameActive = true;
        _miniGameResolved = false;
        // Medical procedures use the timing bar. The rotating ring is reserved
        // exclusively for firearm shots and must never be reused for bandaging.
        _ringMiniGame = false;
        _miniGameElapsed = 0f;
        _barPosition = 0f;
        _barForward = true;
        _ringCompleted = 0;
        _ringSuccesses = 0;
        MiniGameContainer.Visible = true;
        MiniGameVisualContainer.Visible = true;
        _timingBar.Visible = type == CombatPanelTreatmentType.Injection;
        _timingRing.Visible = false;
        _bandageWrap.Visible = type == CombatPanelTreatmentType.Bandage;
        _bandageWrap.Reset();
        MiniGameHitButton.Visible = type == CombatPanelTreatmentType.Injection;
        MiniGameTitleLabel.Text = type == CombatPanelTreatmentType.Bandage
            ? "ПЕРЕВЯЗКА // ФИКСАЦИЯ БИНТА"
            : "ИНЪЕКЦИЯ // ВВЕДЕНИЕ ПРЕПАРАТА";
        MiniGameHintLabel.Text = type == CombatPanelTreatmentType.Bandage
            ? "ЗАЖМИТЕ ЛКМ НА СКРУЧЕННОМ БИНТЕ И ВЕДИТЕ ЕГО ПО КРУГУ ПО ЧАСОВОЙ СТРЕЛКЕ"
            : "ЗАФИКСИРУЙТЕ МОМЕНТ ВВЕДЕНИЯ ПРЕПАРАТА";
        MiniGameHitButton.Text = "НАЖАТЬ ПЛУНЖЕР";
        MiniGameStatusLabel.Text = "ПРОЦЕДУРА ГОТОВА";
        MiniGameHitButton.Disabled = false;
        PerformButton.Disabled = true;
        if (type == CombatPanelTreatmentType.Injection)
        {
            _timingRing.Configure();
            _timingRing.Reset();
        }
        _timingBar.MarkerPosition = 0f;
        if (_target is { } target)
            TreatmentStageRequested?.Invoke(target, item, part, type, CombatPanelTreatmentStage.Begin);
    }

    public bool TryRequestEmote(string message)
    {
        if (_remainingActions <= 0 || EmoteRequested == null)
            return false;

        EmoteRequested.Invoke(message);
        ConsumeTurn();
        return true;
    }

    private bool TryRequestAttack(
        string message,
        TargetBodyPart targetPart,
        CombatPanelAttackType attackType,
        int successfulHits,
        CombatPanelAttackQuality quality)
    {
        if (_remainingActions <= 0 || _target == null || EmoteRequested == null || AttackRequested == null)
            return false;

        AttackRequested.Invoke(targetPart, attackType, successfulHits, quality);
        EmoteRequested.Invoke(message);
        ConsumeTurn();
        return true;
    }

    public void SetRemainingActions(int actions)
    {
        _remainingActions = Math.Clamp(actions, 0, MaxActionsPerTurn);
        UpdateTurnControls();
        UpdateSelection();
    }

    public void ConsumeTurn()
    {
        if (_remainingActions <= 0)
            return;

        _remainingActions--;
        UpdateTurnControls();
        UpdateSelection();
    }

    private void UpdateTurnControls()
    {
        TurnCountLabel.Text = $"ОСТАЛОСЬ ДЕЙСТВИЙ: {_remainingActions}/{MaxActionsPerTurn}";
        TurnStateLabel.Text = _remainingActions <= 0
            ? "Ожидание двух действий соперника"
            : "Можно действовать";

        ShootButton.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        StabButton.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        PunchButton.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        KickButton.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        PerformButton.Disabled = _miniGameActive || _miniGameResolved || _remainingActions <= 0
            || _selectedAction == null
            || _selectedPart == null;

        foreach (var child in MedicalItemsContainer.Children)
        {
            if (child is Button button)
                button.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        }

        foreach (var child in TreatmentItemsContainer.Children)
        {
            if (child is Button button)
                button.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved
                    || _selectedTreatmentPart == null || _target == null;
        }

        foreach (var button in new[]
        {
            TreatmentHeadButton, TreatmentChestButton, TreatmentLeftArmButton,
            TreatmentRightArmButton, TreatmentLeftLegButton, TreatmentRightLegButton,
        })
        {
            button.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        }

        foreach (var child in AmmunitionContainer.Children)
        {
            if (child is Button button)
                button.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved
                    || !_ammunitionButtonAvailability.GetValueOrDefault(button);
        }
    }


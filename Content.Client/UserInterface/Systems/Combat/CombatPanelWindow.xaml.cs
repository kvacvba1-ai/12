    private static void ApplyIndustrialTypography(Control control)
    {
        if (control is Label label)
        {
            label.FontColorOverride = label.StyleClasses.Contains("LabelHeading")
                ? new Color(229, 207, 160)
                : label.StyleClasses.Contains("LabelBig")
                    ? new Color(218, 188, 132)
                    : label.StyleClasses.Contains("LabelSmall")
                        ? new Color(169, 151, 116)
                        : new Color(211, 198, 164);
        }

        foreach (var child in control.Children)
            ApplyIndustrialTypography(child);
    }

    private static void SetMousePassThrough(Control control)
    {
        // Buttons keep their own handling mode; all structural controls must let
        // the event reach their descendants before deciding whether to consume it.
        if (control is not Button)
            control.MouseFilter = MouseFilterMode.Pass;

        foreach (var child in control.Children)
            SetMousePassThrough(child);
    }

    // The header is our own hit-test region. BaseWindow supplies the actual drag/resize machinery.
    // Keep the close-button corner outside the drag region so its click remains unambiguous.
    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        // A wider hit target makes resizing practical on touchpads and high-DPI displays.
        const float edge = 14f;
        const float headerHeight = 58f;

        var mode = DragMode.None;
        if (relativeMousePos.Y < edge)
            mode |= DragMode.Top;
        else if (relativeMousePos.Y > Size.Y - edge)
            mode |= DragMode.Bottom;

        if (relativeMousePos.X < edge)
            mode |= DragMode.Left;
        else if (relativeMousePos.X > Size.X - edge)
            mode |= DragMode.Right;

        if (mode != DragMode.None)
            return mode;

        // The rightmost header area is reserved for the close control.
        if (relativeMousePos.Y < headerHeight && relativeMousePos.X < Size.X - 104f)
            return DragMode.Move;

        return DragMode.None;
    }


    /// <summary>
    /// The custom navigation rail replaces TabContainer's built-in tabs.
    /// Explicit visibility prevents inactive pages from bleeding through
    /// when the container is resized or its children are re-laid out.
    /// </summary>
    private void ApplyTabVisibility(int index)
    {
        CombatTab.Visible = index == 0;
        StatusTab.Visible = index == 1;
        EquipmentTab.Visible = index == 2;
    }

    private void UpdateTabNavigation()
    {
        SetTabButtonActive(CombatNavActionsButton, TabContainer.CurrentTab == 0);
        SetTabButtonActive(CombatNavStatusButton, TabContainer.CurrentTab == 1);
        SetTabButtonActive(CombatNavEquipmentButton, TabContainer.CurrentTab == 2);
    }

    private static void SetTabButtonActive(CombatPanelButton button, bool active)
    {
        if (active)
        {
            if (!button.StyleClasses.Contains("CombatTabActive"))
                button.StyleClasses.Add("CombatTabActive");
        }
        else
        {
            button.StyleClasses.Remove("CombatTabActive");
        }
    }

    public void SetAvailableActions(bool hasGun, bool hasMeleeWeapon)
    {
        var shootVisible = ShootButton.Visible;
        var stabVisible = StabButton.Visible;
        var punchVisible = PunchButton.Visible;
        var kickVisible = KickButton.Visible;

        if (shootVisible == hasGun
            && stabVisible == (!hasGun && hasMeleeWeapon)
            && punchVisible == (!hasGun && !hasMeleeWeapon)
            && kickVisible == (!hasGun && !hasMeleeWeapon))
        {
            UpdateTurnControls();
            return;
        }

        ShootButton.Visible = hasGun;
        StabButton.Visible = !hasGun && hasMeleeWeapon;
        PunchButton.Visible = !hasGun && !hasMeleeWeapon;
        KickButton.Visible = !hasGun && !hasMeleeWeapon;

        _selectedAction = null;
        _selectedPart = null;
        TargetZoneFrame.Visible = false;
        UpdatePartButtonHighlights();
        UpdateActionButtonHighlights();
        UpdateSelection();
        UpdateTurnControls();
    }

    public void SetAmmunitionItems(IEnumerable<(string Name, string Details, bool IsAvailable, Action Use)> items)
    {
        _ammunitionButtonAvailability.Clear();
        AmmunitionContainer.RemoveAllChildren();

        foreach (var (name, details, isAvailable, use) in items)
        {
            var button = new CombatPanelButton
            {
                Text = $"{name} - {details}",
                HorizontalExpand = true,
                                Disabled = _remainingActions <= 0 || !isAvailable,
            };
            _ammunitionButtonAvailability[button] = isAvailable;

            button.OnPressed += _ =>
            {
                if (_remainingActions <= 0 || !isAvailable)
                    return;

                use();
            };

            AmmunitionContainer.AddChild(button);
        }

        var hasAmmunition = AmmunitionContainer.ChildCount > 0;
        AmmunitionToggleButton.Disabled = !hasAmmunition;
        AmmunitionEmptyLabel.Visible = !hasAmmunition;
        if (!hasAmmunition)
            AmmunitionContainer.Visible = false;

        AmmunitionToggleButton.Text = AmmunitionContainer.Visible
            ? "Скрыть боеприпасы"
            : "Показать боеприпасы";
    }


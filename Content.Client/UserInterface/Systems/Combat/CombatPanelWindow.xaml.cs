using Content.Client.UserInterface.Controls;
using Robust.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.UserInterface.Systems.Combat;

[GenerateTypedNameReferences]
public sealed partial class CombatPanelWindow : FancyWindow
{
    private string? _selectedAction;
    private string? _selectedPart;
    private EntityUid? _target;
    private string _targetName = "неизвестная цель";
    public EntityUid? Target => _target;

    public event Action<string>? EmoteRequested;

    public CombatPanelWindow()
    {
        RobustXamlLoader.Load(this);

        ShootButton.OnPressed += _ => SelectAction("shoots");
        StabButton.OnPressed += _ => SelectAction("stabs");
        PunchButton.OnPressed += _ => SelectAction("punches");
        KickButton.OnPressed += _ => SelectAction("kicks");

        HeadButton.OnPressed += _ => SelectPart("head");
        ChestButton.OnPressed += _ => SelectPart("chest");
        LeftArmButton.OnPressed += _ => SelectPart("left arm");
        RightArmButton.OnPressed += _ => SelectPart("right arm");
        LeftLegButton.OnPressed += _ => SelectPart("left leg");
        RightLegButton.OnPressed += _ => SelectPart("right leg");

        PerformButton.OnPressed += _ => Perform();
    }

    /// <summary>
    /// Shows only actions supported by the item in the active hand.
    /// Empty hands expose unarmed actions; guns expose shooting; melee weapons expose stabbing.
    /// </summary>
    public void SetTarget(EntityUid target, string targetName)
    {
        _target = target;
        _targetName = targetName;
        TargetNameLabel.Text = $"Цель: {targetName}";
        _selectedPart = null;
        UpdatePartButtonHighlights();
        UpdateActionButtonHighlights();
        UpdateSelection();
    }

    public void SetHealthAnalyzer(string status, string damage)
    {
        HealthAnalyzerLabel.Text = $"Состояние: {status}\nОбщий урон: {damage}";
    }

    public void SetAvailableActions(bool hasGun, bool hasMeleeWeapon)
    {
        ShootButton.Visible = hasGun;
        StabButton.Visible = !hasGun && hasMeleeWeapon;
        PunchButton.Visible = !hasGun && !hasMeleeWeapon;
        KickButton.Visible = !hasGun && !hasMeleeWeapon;

        _selectedAction = null;
        _selectedPart = null;
        UpdatePartButtonHighlights();
        UpdateActionButtonHighlights();
        UpdateSelection();
    }

    private void SelectAction(string action)
    {
        _selectedAction = action;
        _selectedPart = null;
        BodyPartSelectionContainer.Visible = action is "punches" or "kicks";
        UpdatePartButtonHighlights();
        UpdateActionButtonHighlights();
        UpdateSelection();
    }

    private void SelectPart(string part)
    {
        _selectedPart = part;
        UpdatePartButtonHighlights();
        UpdateSelection();
    }

    private void UpdatePartButtonHighlights()
    {
        var buttons = new[]
        {
            (HeadButton, "head"),
            (ChestButton, "chest"),
            (LeftArmButton, "left arm"),
            (RightArmButton, "right arm"),
            (LeftLegButton, "left leg"),
            (RightLegButton, "right leg"),
        };

        foreach (var (button, part) in buttons)
        {
            if (part == _selectedPart)
                button.StyleClasses.Add("positive");
            else
                button.StyleClasses.Remove("positive");
        }
    }

    private void UpdateActionButtonHighlights()
    {
        var buttons = new[]
        {
            (ShootButton, "shoots"),
            (StabButton, "stabs"),
            (PunchButton, "punches"),
            (KickButton, "kicks"),
        };

        foreach (var (button, action) in buttons)
        {
            if (action == _selectedAction)
                button.StyleClasses.Add("positive");
            else
                button.StyleClasses.Remove("positive");
        }
    }

    public void SetHealthDoll(EntityUid? entity)
    {
        HealthDollView.Visible = entity != null;
        if (entity is { } uid)
            HealthDollView.SetEntity(uid);
    }

    public void SetMedicalItems(IEnumerable<(string Name, Action Use)> items)
    {
        MedicalItemsContainer.RemoveAllChildren();
        foreach (var (name, use) in items)
        {
            var button = new Button
            {
                Text = $"Использовать {name}",
                HorizontalExpand = true,
            };
            button.OnPressed += _ => use();
            MedicalItemsContainer.AddChild(button);
        }
        MedicalItemsContainer.Visible = MedicalItemsContainer.ChildCount > 0;
    }

    private void UpdateSelection()
    {
        var needsPart = _selectedAction is "punches" or "kicks";
        PerformButton.Disabled = _selectedAction == null || needsPart && _selectedPart == null;
        SelectionLabel.Text = _selectedAction == null
            ? "Выбери действие"
            : needsPart && _selectedPart == null
                ? "Выбери часть тела"
                : needsPart
                    ? $"{GetActionLabel(_selectedAction)} → {_selectedPart}"
                    : GetActionLabel(_selectedAction);
    }

    private static string GetActionLabel(string action)
    {
        return action switch
        {
            "shoots" => "Выстрелить",
            "stabs" => "Ударить ножом",
            "punches" => "Ударить кулаком",
            "kicks" => "Пнуть",
            _ => action,
        };
    }

    private void Perform()
    {
        if (_selectedAction == null || _selectedAction is "punches" or "kicks" && _selectedPart == null)
            return;

        var message = _selectedAction switch
        {
            "shoots" => $"shoots at {_targetName}",
            "stabs" => $"stabs {_targetName}",
            "punches" => $"punches {_targetName} in the {_selectedPart}",
            "kicks" => $"kicks {_targetName} in the {_selectedPart}",
            _ => null,
        };

        if (message != null)
            EmoteRequested?.Invoke(message);
    }
}

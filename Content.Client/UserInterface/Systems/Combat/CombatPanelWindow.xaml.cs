    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!_miniGameActive)
            return;

        _miniGameElapsed += args.DeltaSeconds;
        if (_ringMiniGame)
        {
            if (_timingRing.Advance(args.DeltaSeconds))
            {
                // The needle gets exactly one revolution. Any unresolved shot
                // is finalized as soon as it reaches the end of the dial.
                ResolveMiniGame(forceMiss: _ringSuccesses == 0);
                return;
            }
        }
        else
        {
            const float speed = 1.65f;
            _barPosition += (_barForward ? 1 : -1) * args.DeltaSeconds * speed;
            if (_barPosition >= 1f) { _barPosition = 1f; _barForward = false; }
            else if (_barPosition <= 0f) { _barPosition = 0f; _barForward = true; }
            _timingBar.MarkerPosition = _barPosition;
        }

        if (_miniGameElapsed >= 8f)
            ResolveMiniGame(forceMiss: true);
    }

    private void BeginMiniGame(string message, bool radial)
    {
        _pendingAttackMessage = message;
        _miniGameActive = true;
        _ringMiniGame = radial;
        _miniGameElapsed = 0f;
        _barPosition = 0f;
        _barForward = true;
        _ringCompleted = 0;
        _ringSuccesses = 0;
        MiniGameContainer.Visible = true;
        MiniGameVisualContainer.Visible = true;
        _timingBar.Visible = !radial;
        _timingRing.Visible = radial;
        MiniGameTitleLabel.Text = radial ? "БАЛЛИСТИЧЕСКИЙ КОНТРОЛЬ" : "КОНТРОЛЬ УДАРА";
        MiniGameHintLabel.Text = radial
            ? $"ПОПЫТКИ: {RingAttemptsPerAttack}. Попадайте в один из двух красных секторов"
            : "Зафиксируйте удар, когда ползунок окажется в зелёной зоне";
        MiniGameHitButton.Text = "ЗАФИКСИРОВАТЬ";
        MiniGameStatusLabel.Text = "ОЖИДАНИЕ МОМЕНТА...";
        MiniGameHitButton.Disabled = false;
        PerformButton.Disabled = true;
        _timingRing.Configure();
        _timingRing.Reset();
        _timingBar.MarkerPosition = 0f;
    }

    private void RegisterRingHit()
    {
        if (!_miniGameActive || !_ringMiniGame)
            return;

        if (_timingRing.IsInTargetSector)
        {
            _ringSuccesses++;
            AttackSoundRequested?.Invoke(true);
        }

        _ringCompleted++;
        if (_ringCompleted >= RingAttemptsPerAttack)
        {
            ResolveMiniGame();
            return;
        }

        _timingRing.AdvanceTarget();
        MiniGameHitButton.Text = $"ПОПАДАНИЕ {_ringCompleted + 1}/{RingAttemptsPerAttack}";
        MiniGameStatusLabel.Text = $"СЛЕДУЮЩАЯ ПОПЫТКА // {_ringCompleted + 1} ИЗ {RingAttemptsPerAttack}";
    }

    private void ResolveMiniGame(bool forceMiss = false)
    {
        if (!_miniGameActive || _pendingAttackMessage == null)
            return;

        var quality = "неудачно";
        if (!forceMiss)
        {
            if (_ringMiniGame)
            {
                var successes = _ringSuccesses;
                quality = successes == RingAttemptsPerAttack ? "точно" : successes > 0 ? "удачно" : "мимо";
            }
            else
            {
                var distance = MathF.Abs(_barPosition - 0.5f);
                quality = distance <= TimingBarControl.PerfectHalfWidth ? "идеально"
                    : distance <= TimingBarControl.GoodHalfWidth ? "удачно"
                    : "мимо";
            }
        }

        var message = _ringMiniGame
            ? $"{_pendingAttackMessage} (попаданий: {_ringSuccesses}/{RingAttemptsPerAttack}; {quality})"
            : $"{_pendingAttackMessage} (результат мини-игры: {quality})";

        if (!_ringMiniGame && !forceMiss && (quality is "идеально" or "удачно"))
            AttackSoundRequested?.Invoke(false);
        _miniGameActive = false;
        _miniGameResolved = true;
        _pendingAttackMessage = null;
        MiniGameHitButton.Text = "ПРОДОЛЖИТЬ";
        MiniGameHitButton.Disabled = false;
        MiniGameStatusLabel.Text = quality switch
        {
            "идеально" => "PERFECT // ИДЕАЛЬНО",
            "удачно" or "точно" => "GOOD // УСПЕШНО",
            _ => "MISS // ПРОМАХ",
        };
        TryRequestEmote(message);
        UpdateTurnControls();
        UpdateSelection();
    }

    private void Perform()
    {
        if (_selectedAction == null || _selectedPart == null || _remainingActions <= 0)
            return;

        var part = GetPartLabel(_selectedPart);
        var weapon = string.IsNullOrWhiteSpace(_weaponName) ? "оружия ближнего боя" : $"«{_weaponName}»";

        var message = _selectedAction switch
        {
            "shoots" => $"пытается атаковать «{_targetName}»: стреляет в область «{part}» из {weapon}",
            "stabs" => $"пытается атаковать «{_targetName}»: наносит удар оружием {weapon} в область «{part}»",
            "punches" => $"пытается атаковать «{_targetName}»: бьёт кулаком в область «{part}»",
            "kicks" => $"пытается атаковать «{_targetName}»: наносит удар ногой в область «{part}»",
            _ => null,
        };

        if (message == null)
            return;

        if (_selectedAction is "shoots" or "stabs")
        {
            BeginMiniGame(message, radial: _selectedAction == "shoots");
        }
        else
            TryRequestEmote(message);
    }
}

/// <summary>Draws the rotating timing needle and two target sectors for firearm timing.</summary>
internal sealed class TimingRingControl : Control
{
    private const int TargetSectorCount = 2;
    private static readonly float[] TargetAngles =
    {
        MathF.PI * 7f / 6f,  // 210° — upper-left
        MathF.PI * 25f / 18f // 250° — upper-left
    };

    private float _angle;
    private int _targetCount = TargetSectorCount;
    private int _targetIndex;
    private const float RotationSpeed = MathF.PI * 1.0f;
    private const float SectorHalfWidth = 0.20f;

    public bool IsInTargetSector
    {
        get
        {
            // Both visible sectors are valid hit windows. The highlighted
            // sector only indicates the current focus; it is not the sole hitbox.
            for (var i = 0; i < _targetCount; i++)
            {
                var delta = MathF.Abs(MathF.IEEERemainder(_angle - TargetAngles[i], MathF.Tau));
                if (delta <= SectorHalfWidth)
                    return true;
            }

            return false;
        }
    }

    public void Configure() => _targetCount = TargetSectorCount;
    public void AdvanceTarget() => _targetIndex = (_targetIndex + 1) % _targetCount;
    public void Reset()
    {
        _angle = 0f;
        _targetIndex = 0;
    }

    /// <summary>Advances the needle once and returns true when the full dial has been traversed.</summary>
    public bool Advance(float delta)
    {
        _angle = MathF.Min(_angle + delta * RotationSpeed, MathF.Tau);
        return _angle >= MathF.Tau;
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);
        var size = PixelSizeBox.Size;
        var center = new Vector2(size.X / 2f, size.Y / 2f);
        var radius = MathF.Min(size.X, size.Y) * 0.39f;
        handle.DrawCircle(center, radius + 8f, new Color(155, 145, 126), true);
        handle.DrawCircle(center, radius + 4f, new Color(55, 52, 47), true);
        handle.DrawCircle(center, radius - 7f, new Color(23, 25, 25), true);

        for (var sector = 0; sector < _targetCount; sector++)
        {
            var middle = TargetAngles[sector];
            DrawSector(handle, center, radius, middle - SectorHalfWidth, middle + SectorHalfWidth,
                sector == _targetIndex ? new Color(220, 65, 48) : new Color(175, 65, 52));
        }

        for (var rivet = 0; rivet < 8; rivet++)
        {
            var angle = MathF.Tau * rivet / 8f;
            var point = center + new Vector2(MathF.Cos(angle), MathF.Sin(angle)) * (radius + 6f);
            handle.DrawCircle(point, 2.5f, new Color(205, 190, 160), true);
        }

        var needle = center + new Vector2(MathF.Cos(_angle), MathF.Sin(_angle)) * (radius - 10f);
        handle.DrawLine(center, needle, new Color(245, 226, 190));
        handle.DrawCircle(center, 7f, new Color(195, 180, 151), true);
        handle.DrawCircle(center, 3f, new Color(45, 42, 38), true);
    }

    private static void DrawSector(DrawingHandleScreen handle, Vector2 center, float radius, float start, float end, Color color)
    {
        // Render the full annular hit window so its visible size matches hit testing.
        const int segments = 40;
        var innerRadius = radius * 0.58f;
        var previousOuter = center + new Vector2(MathF.Cos(start), MathF.Sin(start)) * radius;
        var previousInner = center + new Vector2(MathF.Cos(start), MathF.Sin(start)) * innerRadius;

        for (var i = 1; i <= segments; i++)
        {
            var angle = start + (end - start) * i / segments;
            var direction = new Vector2(MathF.Cos(angle), MathF.Sin(angle));
            var outer = center + direction * radius;
            var inner = center + direction * innerRadius;
            handle.DrawLine(inner, outer, color);
            if (i > 1)
            {
                handle.DrawLine(previousOuter, outer, color);
                handle.DrawLine(previousInner, inner, color);
            }

            previousOuter = outer;
            previousInner = inner;
        }

        var startDirection = new Vector2(MathF.Cos(start), MathF.Sin(start));
        var endDirection = new Vector2(MathF.Cos(end), MathF.Sin(end));
        handle.DrawLine(center + startDirection * innerRadius, center + startDirection * radius, color);
        handle.DrawLine(center + endDirection * innerRadius, center + endDirection * radius, color);
    }
}

/// <summary>Undertale-style moving marker timing bar with a fixed green hit window.</summary>
internal sealed class TimingBarControl : Control
{
    // Narrow the melee timing windows to roughly one third of their former width.
    public const float PerfectHalfWidth = 0.04f;
    public const float GoodHalfWidth = 0.12f;

    public float MarkerPosition { get; set; }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);
        var size = PixelSizeBox.Size;
        var y = size.Y / 2f;
        var left = size.X * 0.04f;
        var width = size.X * 0.92f;
        var height = MathF.Max(8f, size.Y * 0.25f);
        handle.DrawRect(UIBox2.FromDimensions(new Vector2(left, y - height / 2f), new Vector2(width, height)), new Color(65, 65, 62));

        var goodLeft = 0.5f - GoodHalfWidth;
        handle.DrawRect(
            UIBox2.FromDimensions(new Vector2(left + width * goodLeft, y - height / 2f),
                new Vector2(width * GoodHalfWidth * 2f, height)), new Color(62, 112, 83));
        var perfectLeft = 0.5f - PerfectHalfWidth;
        handle.DrawRect(
            UIBox2.FromDimensions(new Vector2(left + width * perfectLeft, y - height / 2f),
                new Vector2(width * PerfectHalfWidth * 2f, height)), new Color(112, 174, 119));
        var markerX = left + width * MarkerPosition;
        handle.DrawLine(new Vector2(markerX, y - height), new Vector2(markerX, y + height), new Color(238, 238, 220));
        handle.DrawCircle(new Vector2(markerX, y), 5f, new Color(238, 238, 220));
    }
}

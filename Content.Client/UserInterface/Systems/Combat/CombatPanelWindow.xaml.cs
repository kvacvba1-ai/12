using Content.Client.UserInterface.Controls;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Client.Graphics;
using Robust.Shared.Maths;
using Robust.Shared.Timing;
using System.Numerics;

namespace Content.Client.UserInterface.Systems.Combat;

[GenerateTypedNameReferences]
public sealed partial class CombatPanelWindow : FancyWindow
{
    private const int MaxActionsPerTurn = 2;

    private string? _selectedAction;
    private string? _selectedPart;
    private EntityUid? _target;
    private string _targetName = "неизвестная цель";
    private string? _weaponName;
    private int _remainingActions = MaxActionsPerTurn;
    private bool _isIncoming;
    private readonly Dictionary<Button, bool> _ammunitionButtonAvailability = new();
    private readonly TimingRingControl _timingRing = new();
    private readonly TimingBarControl _timingBar = new();
    private bool _miniGameActive;
    private bool _miniGameResolved;
    private bool _ringMiniGame;
    private float _miniGameElapsed;
    private string? _pendingAttackMessage;
    private float _barPosition;
    private bool _barForward = true;

    public EntityUid? Target => _target;
    public bool IsIncoming => _isIncoming;

    public event Action<string>? EmoteRequested;

    public CombatPanelWindow()
    {
        RobustXamlLoader.Load(this);
        _timingRing.MinSize = new Vector2(190, 190);
        _timingBar.MinSize = new Vector2(300, 54);
        MiniGameVisualContainer.AddChild(_timingRing);
        MiniGameVisualContainer.AddChild(_timingBar);
        _timingRing.Visible = false;
        _timingBar.Visible = false;
        var terminalFrame = new StyleBoxFlat
        {
            BackgroundColor = Color.Black,
            BorderColor = new Color(190, 190, 180),
            BorderThickness = new Thickness(2),
        };
        HeaderFrame.PanelOverride = terminalFrame;
        MiniGameContainer.PanelOverride = terminalFrame;
        CombatTab.PanelOverride = terminalFrame;
        StatusTab.PanelOverride = terminalFrame;
        EquipmentTab.PanelOverride = terminalFrame;

        TabContainer.SetTabTitle(CombatTab, "Действия");
        TabContainer.SetTabTitle(StatusTab, "Состояние");
        TabContainer.SetTabTitle(EquipmentTab, "Снаряжение");

        ShootButton.OnPressed += _ => SelectAction("shoots");
        StabButton.OnPressed += _ => SelectAction("stabs");
        PunchButton.OnPressed += _ => SelectAction("punches");
        KickButton.OnPressed += _ => SelectAction("kicks");

        HeadButton.OnPressed += _ => SelectPart("head");
        ChestButton.OnPressed += _ => SelectPart("chest");
        LeftArmButton.OnPressed += _ => SelectPart("left arm");
        RightArmButton.OnPressed += _ => SelectPart("right arm");
        LeftLegButton.OnPressed += _ => SelectPart("left leg");
        RightLegButton.OnPressed += _ => SelectPart("right leg");

        PerformButton.OnPressed += _ => Perform();
        MiniGameHitButton.OnPressed += _ =>
        {
            if (_miniGameActive)
                ResolveMiniGame();
            else if (_miniGameResolved)
            {
                _miniGameResolved = false;
                MiniGameContainer.Visible = false;
                UpdateTurnControls();
                UpdateSelection();
            }
        };
        AmmunitionToggleButton.OnPressed += _ =>
        {
            AmmunitionContainer.Visible = !AmmunitionContainer.Visible;
            AmmunitionToggleButton.Text = AmmunitionContainer.Visible
                ? "Скрыть боеприпасы"
                : "Показать боеприпасы";
        };
    }

    /// <summary>
    /// Reopening the same encounter refreshes its data without resetting turns or selection.
    /// </summary>
    public void SetTarget(EntityUid target, string targetName, bool incoming = false)
    {
        // The same opponent is the same encounter, regardless of who opened the panel.
        var sameEncounter = _target == target;

        _target = target;
        _targetName = targetName;
        _isIncoming = incoming;

        TargetNameLabel.Text = $"{(incoming ? "Нападающий" : "Цель")}: {targetName}";
        EngagementInfoLabel.Text = incoming
            ? "На вас направлено боевое действие. Вы можете ответить."
            : "Вы выбрали цель для ролевого боевого действия.";

        if (!sameEncounter)
        {
            _selectedAction = null;
            _selectedPart = null;
            _remainingActions = MaxActionsPerTurn;
            BodyPartSelectionContainer.Visible = false;
        }

        UpdatePartButtonHighlights();
        UpdateActionButtonHighlights();
        UpdateSelection();
        UpdateTurnControls();
    }

    public void SetWeaponInfo(string info, string? weaponName = null)
    {
        WeaponInfoLabel.Text = info;
        _weaponName = weaponName;
    }

    public void SetHealthAnalyzer(string status, string damage)
    {
        HealthAnalyzerLabel.Text = $"Состояние: {status}\nОбщие повреждения: {damage}";
    }

    public void SetAvailableActions(bool hasGun, bool hasMeleeWeapon)
    {
        var shootVisible = ShootButton.Visible;
        var stabVisible = StabButton.Visible;
        var punchVisible = PunchButton.Visible;
        var kickVisible = KickButton.Visible;

        if (shootVisible == hasGun
            && stabVisible == (!hasGun && hasMeleeWeapon)
            && punchVisible == (!hasGun && !hasMeleeWeapon)
            && kickVisible == (!hasGun && !hasMeleeWeapon))
        {
            UpdateTurnControls();
            return;
        }

        ShootButton.Visible = hasGun;
        StabButton.Visible = !hasGun && hasMeleeWeapon;
        PunchButton.Visible = !hasGun && !hasMeleeWeapon;
        KickButton.Visible = !hasGun && !hasMeleeWeapon;

        _selectedAction = null;
        _selectedPart = null;
        BodyPartSelectionContainer.Visible = false;
        UpdatePartButtonHighlights();
        UpdateActionButtonHighlights();
        UpdateSelection();
        UpdateTurnControls();
    }

    public void SetAmmunitionItems(IEnumerable<(string Name, string Details, bool IsAvailable, Action Use)> items)
    {
        _ammunitionButtonAvailability.Clear();
        AmmunitionContainer.RemoveAllChildren();

        foreach (var (name, details, isAvailable, use) in items)
        {
            var button = new Button
            {
                Text = $"{name} — {details}",
                HorizontalExpand = true,
                Disabled = _remainingActions <= 0 || !isAvailable,
            };
            _ammunitionButtonAvailability[button] = isAvailable;

            button.OnPressed += _ =>
            {
                if (_remainingActions <= 0 || !isAvailable)
                    return;

                use();
            };

            AmmunitionContainer.AddChild(button);
        }

        AmmunitionToggleButton.Disabled = AmmunitionContainer.ChildCount == 0;
        if (AmmunitionContainer.ChildCount == 0)
            AmmunitionContainer.Visible = false;

        AmmunitionToggleButton.Text = AmmunitionContainer.Visible
            ? "Скрыть боеприпасы"
            : "Показать боеприпасы";
    }

    public void SetMedicalItems(IEnumerable<(string Name, Action Use)> items)
    {
        MedicalItemsContainer.RemoveAllChildren();

        foreach (var (name, use) in items)
        {
            var button = new Button
            {
                Text = $"Оказать себе помощь: {name}",
                HorizontalExpand = true,
                Disabled = _remainingActions <= 0,
            };

            button.OnPressed += _ =>
            {
                if (_remainingActions <= 0)
                    return;

                use();
            };

            MedicalItemsContainer.AddChild(button);
        }

        MedicalItemsContainer.Visible = MedicalItemsContainer.ChildCount > 0;
    }

    public bool TryRequestEmote(string message)
    {
        if (_remainingActions <= 0 || EmoteRequested == null)
            return false;

        EmoteRequested.Invoke(message);
        ConsumeTurn();
        return true;
    }

    public void SetRemainingActions(int actions)
    {
        _remainingActions = Math.Clamp(actions, 0, MaxActionsPerTurn);
        UpdateTurnControls();
        UpdateSelection();
    }

    public void ConsumeTurn()
    {
        if (_remainingActions <= 0)
            return;

        _remainingActions--;
        UpdateTurnControls();
        UpdateSelection();
    }

    private void UpdateTurnControls()
    {
        TurnCountLabel.Text = $"ОСТАЛОСЬ ДЕЙСТВИЙ: {_remainingActions}/{MaxActionsPerTurn}";
        TurnStateLabel.Text = _remainingActions <= 0
            ? "Ожидание двух действий соперника"
            : "Можно действовать";

        ShootButton.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        StabButton.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        PunchButton.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        KickButton.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        PerformButton.Disabled = _miniGameActive || _miniGameResolved || _remainingActions <= 0
            || _selectedAction == null
            || _selectedPart == null;

        foreach (var child in MedicalItemsContainer.Children)
        {
            if (child is Button button)
                button.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        }

        foreach (var child in AmmunitionContainer.Children)
        {
            if (child is Button button)
                button.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved
                    || !_ammunitionButtonAvailability.GetValueOrDefault(button);
        }
    }

    private void SelectAction(string action)
    {
        if (_remainingActions <= 0)
            return;

        _selectedAction = action;
        _selectedPart = null;
        BodyPartSelectionContainer.Visible = true;
        UpdatePartButtonHighlights();
        UpdateActionButtonHighlights();
        UpdateSelection();
    }

    private void SelectPart(string part)
    {
        if (_remainingActions <= 0)
            return;

        _selectedPart = part;
        UpdatePartButtonHighlights();
        UpdateSelection();
    }

    private void UpdatePartButtonHighlights()
    {
        var buttons = new[]
        {
            (HeadButton, "head"),
            (ChestButton, "chest"),
            (LeftArmButton, "left arm"),
            (RightArmButton, "right arm"),
            (LeftLegButton, "left leg"),
            (RightLegButton, "right leg"),
        };

        foreach (var (button, part) in buttons)
        {
            if (part == _selectedPart)
                button.StyleClasses.Add("positive");
            else
                button.StyleClasses.Remove("positive");
        }
    }

    private void UpdateActionButtonHighlights()
    {
        var buttons = new[]
        {
            (ShootButton, "shoots"),
            (StabButton, "stabs"),
            (PunchButton, "punches"),
            (KickButton, "kicks"),
        };

        foreach (var (button, action) in buttons)
        {
            if (action == _selectedAction)
                button.StyleClasses.Add("positive");
            else
                button.StyleClasses.Remove("positive");
        }
    }

    public void SetHealthDoll(EntityUid? entity)
    {
        HealthDollView.Visible = entity != null;
        if (entity is { } uid)
            HealthDollView.SetEntity(uid);
    }

    private void UpdateSelection()
    {
        PerformButton.Disabled = _miniGameActive || _miniGameResolved || _remainingActions <= 0
            || _selectedAction == null
            || _selectedPart == null;

        SelectionLabel.Text = _selectedAction == null
            ? "Выберите действие"
            : _selectedPart == null
                ? "Теперь выберите часть тела"
                : $"{GetActionLabel(_selectedAction)} → {GetPartLabel(_selectedPart)}";
    }

    private static string GetActionLabel(string action)
    {
        return action switch
        {
            "shoots" => "Выстрелить",
            "stabs" => "Ударить оружием",
            "punches" => "Ударить кулаком",
            "kicks" => "Пнуть",
            _ => action,
        };
    }

    private static string GetPartLabel(string part)
    {
        return part switch
        {
            "head" => "голова",
            "chest" => "грудь",
            "left arm" => "левая рука",
            "right arm" => "правая рука",
            "left leg" => "левая нога",
            "right leg" => "правая нога",
            _ => part,
        };
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!_miniGameActive)
            return;

        _miniGameElapsed += args.DeltaSeconds;
        if (_ringMiniGame)
            _timingRing.Advance(args.DeltaSeconds);
        else
        {
            const float speed = 1.65f;
            _barPosition += (_barForward ? 1 : -1) * args.DeltaSeconds * speed;
            if (_barPosition >= 1f) { _barPosition = 1f; _barForward = false; }
            else if (_barPosition <= 0f) { _barPosition = 0f; _barForward = true; }
            _timingBar.Position = _barPosition;
        }

        if (_miniGameElapsed >= 8f)
            ResolveMiniGame(forceMiss: true);
    }

    private void BeginMiniGame(string message, bool radial)
    {
        _pendingAttackMessage = message;
        _miniGameActive = true;
        _ringMiniGame = radial;
        _miniGameElapsed = 0f;
        _barPosition = 0f;
        _barForward = true;
        MiniGameContainer.Visible = true;
        MiniGameVisualContainer.Visible = true;
        _timingBar.Visible = !radial;
        _timingRing.Visible = radial;
        MiniGameTitleLabel.Text = radial ? "БАЛЛИСТИЧЕСКИЙ КОНТРОЛЬ" : "КОНТРОЛЬ УДАРА";
        MiniGameHintLabel.Text = radial
            ? "Нажмите, когда указатель войдёт в один из двух красных секторов"
            : "Зафиксируйте удар, когда ползунок окажется в зелёной зоне";
        MiniGameHitButton.Text = "ЗАФИКСИРОВАТЬ";
        MiniGameStatusLabel.Text = "ОЖИДАНИЕ МОМЕНТА...";
        MiniGameHitButton.Disabled = false;
        PerformButton.Disabled = true;
        _timingRing.Reset();
        _timingBar.Position = 0f;
    }

    private void ResolveMiniGame(bool forceMiss = false)
    {
        if (!_miniGameActive || _pendingAttackMessage == null)
            return;

        var quality = "неудачно";
        if (!forceMiss)
        {
            if (_ringMiniGame)
                quality = _timingRing.IsInTargetSector ? "точно" : "мимо";
            else
            {
                var distance = MathF.Abs(_barPosition - 0.5f);
                quality = distance <= 0.09f ? "идеально" : distance <= 0.22f ? "удачно" : "мимо";
            }
        }

        var message = $"{_pendingAttackMessage} (результат мини-игры: {quality})";
        _miniGameActive = false;
        _miniGameResolved = true;
        _pendingAttackMessage = null;
        MiniGameHitButton.Text = "CONTINUE >>";
        MiniGameHitButton.Disabled = false;
        MiniGameStatusLabel.Text = quality switch
        {
            "идеально" => "PERFECT // ИДЕАЛЬНО",
            "удачно" or "точно" => "GOOD // УСПЕШНО",
            _ => "MISS // ПРОМАХ",
        };
        TryRequestEmote(message);
        UpdateTurnControls();
        UpdateSelection();
    }

    private void Perform()
    {
        if (_selectedAction == null || _selectedPart == null || _remainingActions <= 0)
            return;

        var part = GetPartLabel(_selectedPart);
        var weapon = string.IsNullOrWhiteSpace(_weaponName) ? "оружия ближнего боя" : $"«{_weaponName}»";

        var message = _selectedAction switch
        {
            "shoots" => $"пытается атаковать «{_targetName}»: стреляет в область «{part}» из {weapon}",
            "stabs" => $"пытается атаковать «{_targetName}»: наносит удар оружием {weapon} в область «{part}»",
            "punches" => $"пытается атаковать «{_targetName}»: бьёт кулаком в область «{part}»",
            "kicks" => $"пытается атаковать «{_targetName}»: наносит удар ногой в область «{part}»",
            _ => null,
        };

        if (message == null)
            return;

        if (_selectedAction is "shoots" or "stabs")
            BeginMiniGame(message, radial: _selectedAction == "shoots");
        else
            TryRequestEmote(message);
    }
}

/// <summary>Draws the rotating timing needle and two target sectors for firearm timing.</summary>
internal sealed class TimingRingControl : Control
{
    private float _angle;
    private const float RotationSpeed = MathF.PI * 1.35f;
    public bool IsInTargetSector => (_angle >= 0.55f && _angle <= 1.05f)
        || (_angle >= 3.65f && _angle <= 4.15f);

    public void Reset() => _angle = 0f;
    public void Advance(float delta) => _angle = (_angle + delta * RotationSpeed) % (MathF.PI * 2f);

    protected internal override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);
        var size = PixelSizeBox.Size;
        var center = new Vector2(size.X / 2f, size.Y / 2f);
        var radius = MathF.Min(size.X, size.Y) * 0.39f;
        handle.DrawCircle(center, radius, new Color(205, 205, 190), false);
        handle.DrawCircle(center, radius - 5f, new Color(75, 75, 70), false);
        DrawSector(handle, center, radius, 0.55f, 1.05f, new Color(164, 55, 48));
        DrawSector(handle, center, radius, 3.65f, 4.15f, new Color(164, 55, 48));
        var needle = center + new Vector2(MathF.Cos(_angle), MathF.Sin(_angle)) * (radius - 8f);
        handle.DrawLine(center, needle, new Color(235, 235, 220));
        handle.DrawCircle(center, 5f, new Color(205, 205, 190));
    }

    private static void DrawSector(DrawingHandleScreen handle, Vector2 center, float radius, float start, float end, Color color)
    {
        var previous = center + new Vector2(MathF.Cos(start), MathF.Sin(start)) * radius;
        const int segments = 12;
        for (var i = 1; i <= segments; i++)
        {
            var angle = start + (end - start) * i / segments;
            var next = center + new Vector2(MathF.Cos(angle), MathF.Sin(angle)) * radius;
            handle.DrawLine(previous, next, color);
            previous = next;
        }
    }
}

/// <summary>Undertale-style moving marker timing bar with a fixed green hit window.</summary>
internal sealed class TimingBarControl : Control
{
    public float Position { get; set; }

    protected internal override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);
        var size = PixelSizeBox.Size;
        var y = size.Y / 2f;
        var left = size.X * 0.04f;
        var width = size.X * 0.92f;
        var height = MathF.Max(8f, size.Y * 0.25f);
        handle.DrawRect(UIBox2.FromDimensions(new Vector2(left, y - height / 2f), new Vector2(width, height)), new Color(65, 65, 62));
        handle.DrawRect(UIBox2.FromDimensions(new Vector2(left + width * 0.43f, y - height / 2f), new Vector2(width * 0.14f, height)), new Color(70, 132, 105));
        var markerX = left + width * Position;
        handle.DrawLine(new Vector2(markerX, y - height), new Vector2(markerX, y + height), new Color(238, 238, 220));
        handle.DrawCircle(new Vector2(markerX, y), 5f, new Color(238, 238, 220));
    }
}

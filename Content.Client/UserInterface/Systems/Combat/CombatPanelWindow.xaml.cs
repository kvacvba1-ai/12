    public bool TryRequestEmote(string message)
    {
        if (_remainingActions <= 0 || EmoteRequested == null)
            return false;

        EmoteRequested.Invoke(message);
        ConsumeTurn();
        return true;
    }

    public void SetRemainingActions(int actions)
    {
        _remainingActions = Math.Clamp(actions, 0, MaxActionsPerTurn);
        UpdateTurnControls();
        UpdateSelection();
    }

    public void ConsumeTurn()
    {
        if (_remainingActions <= 0)
            return;

        _remainingActions--;
        UpdateTurnControls();
        UpdateSelection();
    }

    private void UpdateTurnControls()
    {
        TurnCountLabel.Text = $"ОСТАЛОСЬ ДЕЙСТВИЙ: {_remainingActions}/{MaxActionsPerTurn}";
        TurnStateLabel.Text = _remainingActions <= 0
            ? "Ожидание двух действий соперника"
            : "Можно действовать";

        ShootButton.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        StabButton.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        PunchButton.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        KickButton.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        PerformButton.Disabled = _miniGameActive || _miniGameResolved || _remainingActions <= 0
            || _selectedAction == null
            || _selectedPart == null;

        foreach (var child in MedicalItemsContainer.Children)
        {
            if (child is Button button)
                button.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved;
        }

        foreach (var child in AmmunitionContainer.Children)
        {
            if (child is Button button)
                button.Disabled = _remainingActions <= 0 || _miniGameActive || _miniGameResolved
                    || !_ammunitionButtonAvailability.GetValueOrDefault(button);
        }
    }

